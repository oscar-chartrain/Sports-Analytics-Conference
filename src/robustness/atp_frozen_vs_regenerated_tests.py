"""Re-runs the ATP entropy-clutch correlations (Section 5.1) on the regenerated
clutch table and compares them with the frozen table the paper's Section 5
reads, because the script that produced the frozen ATP table was lost.

Reads only committed files: results/atp/step2_full_pool_features.csv (entropy),
step3_clutch_features.csv (frozen clutch) and
step3_clutch_features_reconstructed.csv (regenerated by
src/pipeline/rebuild_clutch_features.py). The empirical-p variant exists only
in the regenerated table. Writes results/applications/atp_frozen_vs_regenerated.csv.
"""
import os

import pandas as pd
from scipy import stats

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
res_dir = os.path.join(ROOT, 'results', 'atp')
ent = pd.read_csv(os.path.join(res_dir, 'step2_full_pool_features.csv'))
tables = {'frozen': pd.read_csv(os.path.join(res_dir, 'step3_clutch_features.csv')),
          'regenerated': pd.read_csv(os.path.join(res_dir, 'step3_clutch_features_reconstructed.csv'))}
rows = []
for name, c in tables.items():
    m = ent.merge(c, on='player')
    m = m[m['transition_entropy_sufficient']]
    for variant in ('p65', 'p60', 'p70', 'tiered', 'empirical'):
        for role in ('serve', 'return'):
            col = f'{role}_clutch_{variant}'
            if col not in m or f'{col}_sufficient' not in m:
                continue
            s = m[m[f'{col}_sufficient']].dropna(subset=[col])
            r, p = stats.pearsonr(s['conditional_normalized_entropy'], s[col])
            rows.append({'table': name, 'variant': variant, 'role': role, 'n': len(s), 'r': r, 'p': p})
out = pd.DataFrame(rows)
out.to_csv(os.path.join(ROOT, 'results', 'applications', 'atp_frozen_vs_regenerated.csv'), index=False)
w = out.pivot_table(index=['variant', 'role'], columns='table', values=['r', 'p'])
both = w.dropna()
print(w.round(3).to_string())
print(f"max |delta r| over variants present in both tables: "
      f"{(both[('r', 'regenerated')] - both[('r', 'frozen')]).abs().max():.4f}")
print(f"smallest p on the regenerated table: {w[('p', 'regenerated')].min():.3f} (Bonferroni threshold 0.005)")
